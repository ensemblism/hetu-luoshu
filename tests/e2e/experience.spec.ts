import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.beforeEach(async ({ page }, info) => {
  await page.addInitScript(({ skipGuide }) => {
    if (skipGuide) localStorage.setItem('hl-guide-seen', 'true')
    else localStorage.removeItem('hl-guide-seen')
    localStorage.setItem('hl-language', 'en')
  }, { skipGuide: !info.title.startsWith('reduced motion') })
})
test('loads the real 3D experience and changes diagrams and relations without errors', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('?lang=en')
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.locator('.scene-number')).toHaveCount(10)
  await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('button', { name: 'Reading view', exact: true }).click()
  await page.waitForTimeout(1000)
  const canvas = await page.locator('canvas').boundingBox()
  await page.locator('canvas').click({ position: { x: canvas!.width / 2, y: canvas!.height / 2 } })
  await expect(page.locator('.selected-number')).toContainText('05')
  await expect(page.locator('.formula')).toHaveText('5 + 5 = 10')
  await page.getByRole('button', { name: 'Number 1', exact: true }).click()
  await expect(page.locator('.formula')).toHaveText('1 + 5 = 6')
  await page.getByRole('button', { name: 'Luoshu', exact: true }).click()
  await page.getByRole('button', { name: 'Balance', exact: true }).click()
  await expect(page.locator('.formula')).toHaveText('9 + 5 + 1 = 15')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.locator('.formula')).toHaveText('2 + 7 + 6 = 15')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await expect(page.locator('.scene-number')).toHaveCount(19)
  await expect(page.locator('.experience')).toHaveAttribute('data-mode', 'compare')
  expect(errors).toEqual([])
})
test('sources stay hidden until hover or focus, then show real bibliographic details', async ({ page }) => {
  await page.goto('?lang=en')
  await expect(page.locator('.source-popover')).toHaveCount(0)
  const mark = page.locator('.work-description .citation-mark')
  await mark.hover()
  await expect(page.locator('.source-popover')).toContainText('《易学启蒙》')
  await expect(page.locator('.source-popover')).toContainText('本图书第一')
  await expect(page.locator('.source-popover')).toContainText('一與六共宗')
  await expect(page.locator('.source-popover a')).toHaveAttribute('href', /wikisource/)
  await page.mouse.move(700, 50)
  await expect(page.locator('.source-popover')).toHaveCount(0)
  await mark.focus()
  await expect(page.locator('.source-popover')).toBeVisible()
  await mark.press('Escape')
  await expect(page.locator('.source-popover')).toHaveCount(0)
})
