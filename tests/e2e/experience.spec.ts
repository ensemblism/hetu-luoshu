test('provides complete SVG interaction when WebGL2 is unavailable', async ({ page }) => {
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (this: HTMLCanvasElement, type: string, ...args: unknown[]) { return type === 'webgl2' ? null : original.apply(this, [type, ...args] as never) } as typeof original
  })
  await page.goto('?lang=en')
  await expect(page.locator('.experience')).toHaveAttribute('data-renderer', 'svg')
  await expect(page.locator('.diagram-svg')).toBeVisible()
  await page.getByRole('button', { name: 'Number 2', exact: true }).click()
  await expect(page.locator('.formula')).toHaveText('2 + 5 = 7')
  await page.getByRole('button', { name: 'Luoshu', exact: true }).click()
  await page.getByRole('button', { name: 'Balance', exact: true }).click()
  await expect(page.locator('.formula')).toContainText('15')
})
